public class LinearSearchSpaceComplexity {

    public static void main(String[] args) {

        System.out.println("Linear Search Space Complexity");
        System.out.println();

        System.out.println("Sample Array = {8, 61, 2, 3, 4, 0}");
        System.out.println();

        System.out.println("Auxiliary Space Complexity:");
        System.out.println("Linear Search uses only a few extra variables");
        System.out.println("such as the index and the target value.");
        System.out.println("It does not create any additional array or data structure.");
        System.out.println();

        System.out.println("Therefore, the auxiliary space complexity is O(1).");
    }
}
